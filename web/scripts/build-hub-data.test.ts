import { describe, expect, it } from "vitest";
import { sections } from "../src/design-system/theme-creator/model/controls.ts";
import { presets } from "../src/design-system/theme-creator/model/presets.ts";
import { resolveTheme } from "../src/design-system/theme-creator/model/resolve.ts";
import { themeVars } from "../src/design-system/theme-creator/model/vars.ts";
import { tierCounts } from "../src/design-system/tokens/stats.ts";
import { hubData, renderHubData } from "./build-hub-data.ts";

describe("hubData (ds-hub R3.4, R3.9)", () => {
  const data = hubData();

  it("counts every token across the tiers, and the tiers", () => {
    expect(data.tokens.total).toBe(
      tierCounts.primitive + tierCounts.semantic + tierCounts.component,
    );
    expect(data.tokens.tiers).toBe(Object.keys(tierCounts).length);
  });

  it("counts the theme creator's categories", () => {
    expect(data.themeCreator.categories).toBe(sections.length);
  });

  it("takes the High contrast panel's values from its preset, as the theme creator applies them", () => {
    const preset = presets.find((candidate) => candidate.id === "high-contrast");

    expect(data.highContrast).toEqual({
      name: preset?.name,
      scheme: preset?.source.base,
      vars: preset && themeVars(resolveTheme(preset.source), "diff"),
    });
    expect(Object.keys(data.highContrast.vars).length).toBeGreaterThan(0);
  });
});

describe("renderHubData", () => {
  const text = renderHubData(hubData());

  it("starts with the generated header and imports only types", () => {
    expect(text.startsWith("// Generated by web/scripts/build-hub-data.ts. Do not edit.\n")).toBe(
      true,
    );
    expect(text).toContain(
      'import type { BuiltInTheme, CustomProperty } from "../theme/apply-theme.ts";',
    );
    expect(text).toContain("export const hubData: {");
  });

  it("has no undefined values", () => {
    expect(text).not.toContain("undefined");
  });
});
