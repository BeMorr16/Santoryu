import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { sections } from "../src/design-system/theme-creator/model/controls.ts";
import { presets } from "../src/design-system/theme-creator/model/presets.ts";
import { resolveTheme } from "../src/design-system/theme-creator/model/resolve.ts";
import { themeVars } from "../src/design-system/theme-creator/model/vars.ts";
import { tierCounts } from "../src/design-system/tokens/stats.ts";
import type { BuiltInTheme, CustomProperty } from "../src/theme/apply-theme.ts";

/** What the hub shows that would otherwise load the token metadata or the theme model (ds-hub R3.9). */
export interface HubData {
  tokens: { total: number; tiers: number };
  themeCreator: { categories: number };
  highContrast: {
    name: string;
    scheme: BuiltInTheme;
    vars: Readonly<Record<CustomProperty, string>>;
  };
}

/** The hub's figures and the High contrast panel's values, from their sources (design §3.2). */
export function hubData(): HubData {
  const highContrast = presets.find((preset) => preset.id === "high-contrast");
  if (!highContrast) throw new Error('No preset with id "high-contrast"');
  return {
    tokens: {
      total: Object.values(tierCounts).reduce((sum, count) => sum + count, 0),
      tiers: Object.keys(tierCounts).length,
    },
    themeCreator: { categories: sections.length },
    highContrast: {
      name: highContrast.name,
      scheme: highContrast.source.base,
      vars: themeVars(resolveTheme(highContrast.source), "diff"),
    },
  };
}

/** The generated module's text. */
export function renderHubData(data: HubData): string {
  return [
    "// Generated by web/scripts/build-hub-data.ts. Do not edit.",
    'import type { BuiltInTheme, CustomProperty } from "../theme/apply-theme.ts";',
    "",
    "export const hubData: {",
    "  tokens: { total: number; tiers: number };",
    "  themeCreator: { categories: number };",
    "  highContrast: {",
    "    name: string;",
    "    scheme: BuiltInTheme;",
    "    vars: Readonly<Record<CustomProperty, string>>;",
    "  };",
    `} = ${JSON.stringify(data, null, 2)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const webDir = fileURLToPath(new URL("..", import.meta.url));
  await writeFile(join(webDir, "src", "generated", "hub-data.ts"), renderHubData(hubData()));
  console.log("Generated the hub's data into src/generated/hub-data.ts.");
}
