import { act, fireEvent, render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { createRef } from "react";
import { renderToString } from "react-dom/server";
import { afterEach, beforeEach, describe, expect, it, onTestFinished, vi } from "vitest";
import { expectNoAxeViolations } from "../../../test/axe.ts";
import { resize } from "../../../test/resize-observer.ts";
import { Icon } from "../Icon/Icon.tsx";
import buttonStyles from "../shared/button-styles.module.css";
import type { IconName } from "../Icon/registry.ts";
import { CodeBlock, COPY_RESET_MS } from "./CodeBlock.tsx";
import styles from "./CodeBlock.module.css";

const css = `
.quiet {
  --component-link-color: var(--color-text-default);

  color: red;
}
`;
const trimmed = css.slice(1, -1);

function preOf(container: HTMLElement) {
  const pre = container.querySelector("pre");
  if (!pre) throw new Error("No pre");
  return pre;
}

/** Gives the pre a layout (jsdom has none) and reports a resize to its observer. */
function setOverflow(pre: HTMLElement, overflowing: boolean) {
  Object.defineProperty(pre, "clientWidth", { configurable: true, value: 300 });
  Object.defineProperty(pre, "scrollWidth", { configurable: true, value: overflowing ? 600 : 300 });
  act(() => {
    resize(pre, 100);
  });
}

function svgMarkup(name: IconName) {
  const holder = document.createElement("div");
  holder.innerHTML = renderToString(<Icon name={name} />);
  return holder.querySelector("svg")?.innerHTML;
}

function copyButton() {
  return screen.getByRole("button", { name: "Copy code" });
}

describe("CodeBlock", () => {
  it("renders a header with the label, then pre > code with the trimmed text (refinement R15.1, R15.2)", () => {
    const { container } = render(<CodeBlock label="CSS">{css}</CodeBlock>);

    const root = container.firstElementChild;
    expect(root?.tagName).toBe("DIV");
    expect(root?.firstElementChild).toHaveTextContent("CSS");
    const code = preOf(container).querySelector(":scope > code");
    // Inner blank lines and indentation are kept; one line break is trimmed at each end.
    expect(code?.textContent).toBe(trimmed);
    expect(code).toHaveClass(styles.code ?? "");
  });

  it("numbers its lines by default, one span per line, with the text unchanged (refinement R15.12)", () => {
    const { container } = render(<CodeBlock label="CSS">{css}</CodeBlock>);

    const pre = preOf(container);
    expect(pre).toHaveClass(styles.numbered ?? "");
    const lines = [...pre.querySelectorAll(`code > .${styles.line ?? ""}`)];
    expect(lines.map((line) => line.textContent)).toEqual(
      trimmed.split("\n").map((line, index, all) => (index < all.length - 1 ? `${line}\n` : line)),
    );
    expect(
      lines.every((line) => line.firstElementChild?.classList.contains(styles.text ?? "")),
    ).toBe(true);
    // The numbers are generated by CSS, so nothing in the markup or the accessible text holds them.
    expect(pre.querySelector("code")?.textContent).toBe(trimmed);
  });

  it("turns line numbers off with lineNumbers={false}", () => {
    const { container } = render(
      <CodeBlock label="CSS" lineNumbers={false}>
        {css}
      </CodeBlock>,
    );

    expect(preOf(container)).not.toHaveClass(styles.numbered ?? "");
    expect(preOf(container).querySelector("code")?.textContent).toBe(trimmed);
  });

  it("trims only one line break at each end", () => {
    const { container } = render(<CodeBlock label="Text">{"\n\na\n\n"}</CodeBlock>);

    expect(preOf(container).textContent).toBe("\na\n");
  });

  it("sets language-<language> on the code (refinement R15.3)", () => {
    const { container } = render(
      <CodeBlock label="CSS" language="css">
        a
      </CodeBlock>,
    );

    expect(container.querySelector("code")).toHaveClass(styles.code ?? "", "language-css");
  });

  it("passes className, native props and the ref to the root", () => {
    const ref = createRef<HTMLDivElement>();
    const { container } = render(
      <CodeBlock label="CSS" ref={ref} className="extra" id="sample" data-x="1">
        a
      </CodeBlock>,
    );

    const root = container.firstElementChild;
    expect(root).toBe(ref.current);
    expect(root).toHaveClass(styles.root ?? "", "extra");
    expect(root).toHaveAttribute("id", "sample");
    expect(root).toHaveAttribute("data-x", "1");
  });

  describe("overflow (refinement R15.5)", () => {
    it("is a focusable group named by the label only while it overflows", () => {
      const { container } = render(<CodeBlock label="Terminal">a</CodeBlock>);
      const pre = preOf(container);

      setOverflow(pre, true);
      expect(pre).toHaveAttribute("tabindex", "0");
      expect(screen.getByRole("group", { name: "Terminal" })).toBe(pre);

      setOverflow(pre, false);
      expect(pre).not.toHaveAttribute("tabindex");
      expect(pre).not.toHaveAttribute("role");
      expect(pre).not.toHaveAttribute("aria-labelledby");

      setOverflow(pre, true);
      expect(pre).toHaveAttribute("tabindex", "0");
    });

    it("watches both the pre and the code", () => {
      const { container } = render(<CodeBlock label="Terminal">a</CodeBlock>);
      const pre = preOf(container);
      setOverflow(pre, false);

      Object.defineProperty(pre, "scrollWidth", { configurable: true, value: 600 });
      act(() => {
        const code = pre.querySelector("code");
        if (code) resize(code, 100);
      });

      expect(pre).toHaveAttribute("tabindex", "0");
    });

    it("keeps a focused block's Tab stop until it blurs, so focus never drops to the body", () => {
      const { container } = render(<CodeBlock label="Terminal">a</CodeBlock>);
      const pre = preOf(container);
      setOverflow(pre, true);
      act(() => {
        pre.focus();
      });

      setOverflow(pre, false);
      expect(pre).toHaveFocus();
      expect(pre).toHaveAttribute("tabindex", "0");

      act(() => {
        pre.blur();
      });
      expect(pre).not.toHaveAttribute("tabindex");
    });

    it("is never focusable with wrap, however wide its content", () => {
      const { container } = render(
        <CodeBlock label="Terminal" wrap>
          a
        </CodeBlock>,
      );
      const pre = preOf(container);

      setOverflow(pre, true);

      expect(pre).not.toHaveAttribute("tabindex");
      expect(pre).not.toHaveAttribute("role");
      expect(pre).toHaveClass(styles.pre ?? "", styles.wrap ?? "");
    });

    it("is prerendered as a focusable group without wrap, and plain with it", () => {
      const holder = document.createElement("div");

      holder.innerHTML = renderToString(<CodeBlock label="Terminal">a</CodeBlock>);
      const pre = holder.querySelector("pre");
      expect(pre).toHaveAttribute("tabindex", "0");
      expect(pre).toHaveAttribute("role", "group");
      const labelId = pre?.getAttribute("aria-labelledby") ?? "";
      expect(holder.querySelector(`[id="${labelId}"]`)).toHaveTextContent("Terminal");

      holder.innerHTML = renderToString(
        <CodeBlock label="Terminal" wrap>
          a
        </CodeBlock>,
      );
      expect(holder.querySelector("pre")).not.toHaveAttribute("tabindex");
      expect(holder.querySelector("pre")).not.toHaveAttribute("role");
    });

    it("hydrates without a mismatch, then drops the Tab stop once it measures as fitting", () => {
      const ui = <CodeBlock label="CSS">a</CodeBlock>;
      const container = document.createElement("div");
      container.innerHTML = renderToString(ui);
      document.body.append(container);
      const onRecoverableError = vi.fn();
      const consoleError = vi.spyOn(console, "error").mockImplementation(() => undefined);

      const { unmount } = render(ui, { container, hydrate: true, onRecoverableError });

      expect(onRecoverableError).not.toHaveBeenCalled();
      expect(consoleError).not.toHaveBeenCalled();
      const pre = preOf(container);
      expect(pre).toHaveAttribute("tabindex", "0");
      setOverflow(pre, false);
      expect(pre).not.toHaveAttribute("tabindex");

      consoleError.mockRestore();
      unmount();
      container.remove();
    });
  });

  describe("copy (refinement R15.6)", () => {
    let writeText: ReturnType<typeof vi.fn<(text: string) => Promise<void>>>;

    beforeEach(() => {
      vi.useFakeTimers({ toFake: ["setTimeout", "clearTimeout"] });
      writeText = vi.fn<(text: string) => Promise<void>>().mockResolvedValue(undefined);
      Object.defineProperty(navigator, "clipboard", {
        configurable: true,
        value: { writeText },
      });
    });

    afterEach(() => {
      vi.useRealTimers();
      Reflect.deleteProperty(navigator, "clipboard");
    });

    async function press() {
      await act(async () => {
        fireEvent.click(copyButton());
        await Promise.resolve();
      });
    }

    it("writes the trimmed code, shows a check and says Copied, then resets after 2s", async () => {
      render(<CodeBlock label="CSS">{css}</CodeBlock>);
      const status = screen.getByRole("status");
      expect(status).toBeEmptyDOMElement();
      expect(copyButton().querySelector("svg")?.innerHTML).toBe(svgMarkup("copy"));

      await press();

      expect(writeText).toHaveBeenCalledWith(trimmed);
      expect(status).toHaveTextContent("Copied");
      expect(copyButton().querySelector("svg")?.innerHTML).toBe(svgMarkup("check"));

      act(() => {
        vi.advanceTimersByTime(COPY_RESET_MS - 1);
      });
      expect(status).toHaveTextContent("Copied");
      act(() => {
        vi.advanceTimersByTime(1);
      });
      expect(status).toBeEmptyDOMElement();
      expect(copyButton().querySelector("svg")?.innerHTML).toBe(svgMarkup("copy"));
    });

    it("restarts the 2s when pressed again, keeping the button's name", async () => {
      render(<CodeBlock label="CSS">a</CodeBlock>);
      const status = screen.getByRole("status");

      await press();
      act(() => {
        vi.advanceTimersByTime(COPY_RESET_MS - 500);
      });
      await press();
      act(() => {
        vi.advanceTimersByTime(COPY_RESET_MS - 1);
      });

      expect(status).toHaveTextContent("Copied");
      expect(copyButton()).toHaveAccessibleName("Copy code");
      act(() => {
        vi.advanceTimersByTime(1);
      });
      expect(status).toBeEmptyDOMElement();
    });

    /** Makes each writeText wait until the test resolves it, in call order. */
    function deferWrites() {
      const pending: (() => void)[] = [];
      writeText.mockImplementation(
        () =>
          new Promise<void>((resolve) => {
            pending.push(resolve);
          }),
      );
      return async (index: number) => {
        await act(async () => {
          pending[index]?.();
          await Promise.resolve();
        });
      };
    }

    it("empties the status as a second press starts, so Copied is announced again", async () => {
      render(<CodeBlock label="CSS">a</CodeBlock>);
      const status = screen.getByRole("status");
      await press();
      expect(status).toHaveTextContent("Copied");
      const resolve = deferWrites();

      act(() => {
        fireEvent.click(copyButton());
      });
      expect(status).toBeEmptyDOMElement();
      await resolve(0);

      expect(status).toHaveTextContent("Copied");
    });

    it("times the reset from the last press to finish when presses overlap", async () => {
      const resolve = deferWrites();
      render(<CodeBlock label="CSS">a</CodeBlock>);
      const status = screen.getByRole("status");

      act(() => {
        fireEvent.click(copyButton());
        fireEvent.click(copyButton());
      });
      await resolve(0);
      act(() => {
        vi.advanceTimersByTime(1000);
      });
      await resolve(1);
      act(() => {
        vi.advanceTimersByTime(COPY_RESET_MS - 1);
      });

      expect(status).toHaveTextContent("Copied");
      act(() => {
        vi.advanceTimersByTime(1);
      });
      expect(status).toBeEmptyDOMElement();
    });

    it("copies from the keyboard with Enter and Space, keeping focus on the button", async () => {
      // Testing Library waits on setTimeout(0), which only runs if it can advance the fake clock.
      vi.stubGlobal("jest", { advanceTimersByTime: (ms: number) => vi.advanceTimersByTime(ms) });
      onTestFinished(() => {
        vi.unstubAllGlobals();
      });
      const user = userEvent.setup({ advanceTimers: (ms) => vi.advanceTimersByTime(ms) });
      // user-event attaches its own clipboard; the stub under test replaces it.
      Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText } });
      render(<CodeBlock label="CSS">a</CodeBlock>);

      await user.tab();
      expect(copyButton()).toHaveFocus();
      await user.keyboard("{Enter}");
      expect(writeText).toHaveBeenCalledTimes(1);
      await waitFor(() => {
        expect(screen.getByRole("status")).toHaveTextContent("Copied");
      });
      await user.keyboard(" ");
      expect(writeText).toHaveBeenCalledTimes(2);
      expect(copyButton()).toHaveFocus();
    });

    it("is a small ghost button that shows its name as a tooltip (refinement R14.12)", () => {
      render(<CodeBlock label="CSS">a</CodeBlock>);

      const button = copyButton();
      expect(button).toHaveClass(buttonStyles.ghost ?? "", buttonStyles.sm ?? "");
      const tooltip = button.nextElementSibling;
      expect(tooltip).toHaveAttribute("popover", "manual");
      expect(tooltip).toHaveAttribute("aria-hidden", "true");
      expect(tooltip).toHaveTextContent("Copy code");
    });

    it("shows and says Couldn't copy, with the warning icon, when the clipboard refuses, then resets after 2s", async () => {
      writeText.mockRejectedValue(new DOMException("Denied", "NotAllowedError"));
      render(<CodeBlock label="CSS">a</CodeBlock>);
      const status = screen.getByRole("status");

      await press();

      expect(status).toHaveTextContent("Couldn't copy");
      expect(copyButton().querySelector("svg")?.innerHTML).toBe(svgMarkup("warning"));
      expect(copyButton()).toHaveAccessibleName("Copy code");
      // Visible for sighted users, hidden from assistive technology so it's announced once.
      const shown = screen.getByText("Couldn't copy", { ignore: '[role="status"]' });
      expect(shown).toBeVisible();
      expect(shown).toHaveAttribute("aria-hidden", "true");
      expect(shown).toHaveClass(styles.failure ?? "");

      act(() => {
        vi.advanceTimersByTime(COPY_RESET_MS);
      });
      expect(status).toBeEmptyDOMElement();
      expect(screen.queryByText("Couldn't copy", { ignore: '[role="status"]' })).toBeNull();
      expect(copyButton().querySelector("svg")?.innerHTML).toBe(svgMarkup("copy"));
    });

    it("shows no failure text after a successful copy", async () => {
      render(<CodeBlock label="CSS">a</CodeBlock>);

      await press();

      expect(screen.queryByText("Copied", { ignore: '[role="status"]' })).toBeNull();
    });

    it("renders no button and no status with copy={false}", () => {
      render(
        <CodeBlock label="CSS" copy={false}>
          a
        </CodeBlock>,
      );

      expect(screen.queryByRole("button")).toBeNull();
      expect(screen.queryByRole("status")).toBeNull();
    });
  });

  it("is reached by Tab after its copy button while it overflows, and Shift+Tab goes back", async () => {
    const user = userEvent.setup();
    const { container } = render(<CodeBlock label="Terminal">a</CodeBlock>);
    const pre = preOf(container);
    setOverflow(pre, true);

    await user.tab();
    expect(copyButton()).toHaveFocus();
    await user.tab();
    expect(pre).toHaveFocus();
    await user.tab({ shift: true });
    expect(copyButton()).toHaveFocus();
  });

  it("has no axe violations fitting, overflowing, and with Copied showing", async () => {
    Object.defineProperty(navigator, "clipboard", {
      configurable: true,
      value: { writeText: () => Promise.resolve() },
    });
    const { container } = render(
      <main>
        <CodeBlock label="CSS">a</CodeBlock>
      </main>,
    );
    const pre = preOf(container);

    setOverflow(pre, false);
    await expectNoAxeViolations(container);
    setOverflow(pre, true);
    await expectNoAxeViolations(container);
    // Fake timers only for the press, so the reset never runs and axe's own timers still do.
    vi.useFakeTimers({ toFake: ["setTimeout", "clearTimeout"] });
    await act(async () => {
      fireEvent.click(copyButton());
      await Promise.resolve();
    });
    vi.useRealTimers();
    expect(screen.getByRole("status")).toHaveTextContent("Copied");
    await expectNoAxeViolations(container);

    Reflect.deleteProperty(navigator, "clipboard");
  });
});
